class ServerTestCase(unittest.TestCase):
    """Fresh storage per test; uploads open (no API key, no signature) unless a test tightens them."""

    def setUp(self) -> None:
        self.temp_dir = Path(tempfile.mkdtemp(prefix="update-server-tests-"))
        self._saved = {
            (module, name): getattr(module, name)
            for module, name in [
                (app_config, "UPDATE_STORAGE_DIR"),
                (app_config, "MAX_UPLOAD_REQUEST_SIZE_BYTES"),
                (app_storage, "UPDATE_STORAGE_DIR"),
                (app_security, "ADMIN_API_KEY"),
                (app_security, "ALLOW_UNAUTHENTICATED_UPLOADS"),
                (app_signing, "SIGNING_PUBLIC_KEY_FILE"),
                (app_signing, "ALLOW_UNSIGNED_UPLOADS"),
            ]
        }
        app_config.UPDATE_STORAGE_DIR = self.temp_dir
        app_storage.UPDATE_STORAGE_DIR = self.temp_dir
        app_security.ADMIN_API_KEY = None
        app_security.ALLOW_UNAUTHENTICATED_UPLOADS = True
        app_signing.SIGNING_PUBLIC_KEY_FILE = None
        app_signing.ALLOW_UNSIGNED_UPLOADS = True
        self.client = TestClient(app)

    def tearDown(self) -> None:
        for (module, name), value in self._saved.items():
            setattr(module, name, value)
        shutil.rmtree(self.temp_dir, ignore_errors=True)

    def _upload(
        self, version: str = "1.0.0", target: str = "controller", files=None, headers=None, client=None, channel_override="stable", **fields
    ):
        return (client or self.client).post(
            UPLOAD_URL,
            data={"channel": channel_override, "version": version, "target": target, **fields},
            files=files or [("files", ("firmware.bin", b"firm", "application/octet-stream"))],
            headers=headers or {},
        )


    def assert_stylesheet_covers(self, pages: list[str]) -> None:
        # flash.css is generated by Tailwind from the template (npm run build:css) and committed. A class
        # that is used on the page but missing from the stylesheet means the build was not rerun.
        stylesheet = (REPO_ROOT / "update_server" / "static" / "flash.css").read_text()
        classes = {name for page in pages for attribute in re.findall(r'class="([^"]*)"', page) for name in attribute.split()}
        self.assertGreater(len(classes), 40)
        missing = sorted(
            name for name in classes if "." + re.sub(r"([^A-Za-z0-9_-])", r"\\\1", name) not in stylesheet
        )
        self.assertEqual(missing, [], "run `npm run build:css` and commit update_server/static/flash.css")


