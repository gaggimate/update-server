    @classmethod
    def setUpClass(cls) -> None:
        cls.key = Ed25519PrivateKey.generate()
        cls.other_key = Ed25519PrivateKey.generate()

    def setUp(self) -> None:
        super().setUp()
        self.key_file = self.temp_dir / "release-signing-key.pub.pem"
        self.key_file.write_bytes(public_pem(self.key))
